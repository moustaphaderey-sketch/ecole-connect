@Composable
fun ChildSelectorBar(
    students: List<Student>,
    selectedChildId: String?,
    onSelectChild: (String) -> Unit,
    modifier: Modifier = Modifier
) {
    if (students.isEmpty()) return
    val activeId = selectedChildId?.takeIf { id -> students.any { it.id == id } } ?: students.first().id

    Column(modifier = modifier.fillMaxWidth()) {
        Text(
            text = "Enfant suivi (${students.size})",
            style = MaterialTheme.typography.labelMedium,
            color = MaterialTheme.colorScheme.onSurfaceVariant
        )
        Spacer(modifier = Modifier.height(6.dp))
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .horizontalScroll(rememberScrollState()),
            horizontalArrangement = Arrangement.spacedBy(8.dp)
        ) {
            students.forEach { child ->
                val selected = child.id == activeId
                FilterChip(
                    selected = selected,
                    onClick = { onSelectChild(child.id) },
                    modifier = Modifier.testTag("child_chip_${child.id}"),
                    label = {
                        Text("${child.fullName} (${child.className})")
                    },
                    leadingIcon = {
                        Icon(
                            imageVector = if (selected) Icons.Filled.Check else Icons.Outlined.ChildCare,
                            contentDescription = null,
                            modifier = Modifier.size(18.dp)
                        )
                    },
                    colors = FilterChipDefaults.filterChipColors(
                        selectedContainerColor = MaterialTheme.colorScheme.primaryContainer,
                        selectedLabelColor = MaterialTheme.colorScheme.onPrimaryContainer
                    )
                )
            }
        }
    }
}

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun <T> DropdownSelector(
    label: String,
    options: List<T>,
    selectedOption: T?,
    optionLabel: (T) -> String,
    onOptionSelected: (T) -> Unit,
    modifier: Modifier = Modifier,
    emptyLabel: String = "Aucune option disponible"
) {
    var expanded by remember { mutableStateOf(false) }

    ExposedDropdownMenuBox(
        expanded = expanded,
        onExpandedChange = { if (options.isNotEmpty()) expanded = !expanded },
        modifier = modifier.fillMaxWidth()
    ) {
        OutlinedTextField(
            value = selectedOption?.let(optionLabel) ?: if (options.isEmpty()) emptyLabel else "Sélectionner...",
            onValueChange = {},
            readOnly = true,
            label = { Text(label) },
            trailingIcon = {
                ExposedDropdownMenuDefaults.TrailingIcon(expanded = expanded)
            },
            modifier = Modifier
                .fillMaxWidth()
                .menuAnchor(MenuAnchorType.PrimaryNotEditable, enabled = options.isNotEmpty())
        )
        ExposedDropdownMenu(
            expanded = expanded,
            onDismissRequest = { expanded = false }
        ) {
            options.forEach { item ->
                DropdownMenuItem(
                    text = { Text(optionLabel(item)) },
                    onClick = {
                        onOptionSelected(item)
                        expanded = false
                    }
                )
            }
        }
    }
}

@Composable
fun TabChipsRow(
    tabs: List<String>,
    selectedIndex: Int,
    onSelectTab: (Int) -> Unit,
    modifier: Modifier = Modifier
) {
    Row(
        modifier = modifier
            .fillMaxWidth()
            .horizontalScroll(rememberScrollState()),
        horizontalArrangement = Arrangement.spacedBy(8.dp)
    ) {
        tabs.forEachIndexed { index, title ->
            FilterChip(
                selected = selectedIndex == index,
                onClick = { onSelectTab(index) },
                modifier = Modifier.testTag("tab_chip_$index"),
                label = { Text(title) },
                colors = FilterChipDefaults.filterChipColors(
                    selectedContainerColor = MaterialTheme.colorScheme.primary,
                    selectedLabelColor = MaterialTheme.colorScheme.onPrimary
                )
            )
        }
    }
}
